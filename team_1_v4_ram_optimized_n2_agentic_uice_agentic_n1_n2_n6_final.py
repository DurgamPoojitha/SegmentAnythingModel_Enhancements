"""---
## Agentic UICE Enhancement: N1 → N2 → N6

Implements the architecture diagram pipeline strictly in order.

| Module | Role | Question |
|--------|------|---------|
| **N1** | Aleatoric vs Epistemic Decomposition | WHERE to refine |
| **N2** | Automatic SAM Prompt Generation | HOW to refine |
| **N6** | Agentic Controller & Explainability | HOW MUCH / WHY |

**N1 must run first** — its `epi_mask` output is the required input to N2.

---
## N1 — Aleatoric vs Epistemic Uncertainty Decomposition
**WHERE to refine** (runs before N2, gates it)

| Type | Meaning | N2 Action |
|------|---------|-----------|
| **Epistemic** | Model uncertainty — correctable with better prompts | ✅ N2 generates prompts |
| **Aleatoric** | Data noise — inherently ambiguous, cannot be fixed | ❌ N2 skipped entirely |

**Formula (BALD criterion):**
```
Epistemic  =  Predictive Entropy  −  Expected Entropy
Aleatoric  =  Expected Entropy
```

**Key design decision:** N1 uses *relative* thresholding on the normalized epistemic map,
not an absolute threshold on raw BALD values. This is essential because score-perturbation-based
uncertainty produces small absolute values (~1e-3 to 1e-2) that vary by image content.
A relative threshold detects spatial variation correctly regardless of absolute magnitude.

**Compute:** 1 real SAM call + 3 score perturbations = 4 passes total.
All passes reuse the cached image embedding — no repeated encoder inference.
"""

# =====================================================
# N1: Aleatoric vs Epistemic Uncertainty Decomposition
# =====================================================
# Runs FIRST. Output (epi_mask, epi_ratio) feeds N2.
#
# IMPLEMENTATION NOTE:
# Score-perturbation stochastic inference produces
# low-variance epistemic maps because SAM is near-
# deterministic. Therefore N1 uses BOUNDARY-FOCUSED
# analysis: we compare epistemic vs aleatoric uncertainty
# specifically in the nucleus boundary ring, which is
# the only region where refinement matters.
#
# N1 always produces a mask for N2 — it never hard-blocks
# on a flat map. Instead it returns epi_ratio which N6
# uses to decide how aggressively N2 should refine.
#
# RAM-safe: all stochastic temporaries deleted per pass.
# Uses F and binary_dilation already imported in cell 4.
# =====================================================

def n1_stochastic_passes(predictor, point_coords, point_labels,
                          bbox=None, n_passes=4, noise_std=0.08):
    """
    N1 Step 1: Lightweight stochastic inference.

    ONE real SAM call (cached image embedding) +
    (n_passes-1) score perturbations.
    No repeated encoder calls — fast and RAM-safe.

    Returns:
        prob_maps  : list of (H,W) float32 foreground probability maps
        base_mask  : (H,W) bool  — best mask from the real SAM call
        base_score : float       — confidence of base_mask
    """
    prob_maps  = []
    base_mask  = None
    base_score = 0.0

    try:
        with torch.no_grad():
            if bbox is not None:
                mp, sc, _ = predictor.predict(box=bbox, multimask_output=True)
            else:
                mp, sc, _ = predictor.predict(
                    point_coords=point_coords,
                    point_labels=point_labels,
                    multimask_output=True)

        best_idx   = int(np.argmax(sc))
        base_mask  = mp[best_idx].astype(bool)
        base_score = float(sc[best_idx])

        # Pass 1: real scores → foreground probability map
        probs_r = F.softmax(torch.tensor(sc, dtype=torch.float32), dim=0)
        masks_t = torch.tensor(mp.astype(np.float32))
        p_fg    = (probs_r[:, None, None] * masks_t).sum(0).clamp(1e-7, 1 - 1e-7)
        prob_maps.append(p_fg.numpy().copy())
        del p_fg

        # Passes 2..n_passes: perturb scores, reuse masks_t
        for _ in range(n_passes - 1):
            noise   = np.random.normal(0, noise_std, sc.shape).astype(np.float32)
            sc_n    = sc + noise
            probs_n = F.softmax(torch.tensor(sc_n, dtype=torch.float32), dim=0)
            p_n     = (probs_n[:, None, None] * masks_t).sum(0).clamp(1e-7, 1 - 1e-7)
            prob_maps.append(p_n.numpy().copy())
            del probs_n, p_n, noise, sc_n

        del probs_r, masks_t, mp, sc

    except Exception:
        pass  # caller checks for empty prob_maps

    return prob_maps, base_mask, base_score


def n1_predictive_entropy(prob_maps):
    """H[p(y|x)] = entropy of the mean. Total uncertainty."""
    if not prob_maps:
        return np.zeros((1, 1), dtype=np.float32)
    p_mean = np.stack(prob_maps, axis=0).mean(axis=0).clip(1e-7, 1 - 1e-7)
    ent    = -(p_mean * np.log(p_mean) + (1 - p_mean) * np.log(1 - p_mean))
    del p_mean
    return ent.astype(np.float32)


def n1_expected_entropy(prob_maps):
    """E[H[p(y|x,w)]] = mean of per-pass entropies. Aleatoric component."""
    if not prob_maps:
        return np.zeros((1, 1), dtype=np.float32)
    per = []
    for p in prob_maps:
        pc = np.clip(p, 1e-7, 1 - 1e-7)
        per.append(-(pc * np.log(pc) + (1 - pc) * np.log(1 - pc)))
        del pc
    return np.stack(per, axis=0).mean(axis=0).astype(np.float32)


def n1_epistemic(pred_ent, exp_ent):
    """Epistemic = Predictive - Aleatoric (BALD). N2 corrective target."""
    return np.clip(pred_ent - exp_ent, 0.0, None).astype(np.float32)


def n1_aleatoric(exp_ent):
    """Aleatoric = Expected entropy. Data noise — N2 avoids these regions."""
    return np.clip(exp_ent, 0.0, None).astype(np.float32)


def n1_normalize(m):
    """
    Normalize map to [0,1]. Handles flat maps safely.
    Used for relative comparison — not absolute thresholds.
    """
    mn, mx = float(m.min()), float(m.max())
    if mx - mn < 1e-10:
        return np.zeros_like(m, dtype=np.float32)
    return ((m - mn) / (mx - mn)).astype(np.float32)


def n1_analyze(epi_map, ale_map, base_mask):
    """
    N1 Analysis: boundary-focused epistemic vs aleatoric classification.

    KEY DESIGN: We analyze uncertainty only in the BOUNDARY RING
    (4px dilation of the mask minus the mask interior). This is the
    only region where SAM refinement can improve the segmentation.

    Unlike a hard gate, n1_analyze always returns an epi_mask for N2.
    The epi_ratio tells N6 how confident to be in the refinement.

    Returns:
        should_refine (bool)         — hint: True if epi dominates boundary
        reason        (str)          — for N6 explanation
        epi_ratio     (float)        — epistemic fraction in boundary ring
        epi_mask      (ndarray bool) — pixels N2 should focus on
    """
    H, W = epi_map.shape[:2]

    # Build boundary ring: 4px dilation minus mask interior
    if base_mask is not None and base_mask.any():
        dilated      = binary_dilation(base_mask, disk(4))
        boundary_ring = dilated & ~base_mask
    else:
        # No mask: use full image center region
        boundary_ring = np.ones((H, W), dtype=bool)

    # Normalize both maps
    epi_n = n1_normalize(epi_map)
    ale_n = n1_normalize(ale_map)

    # Extract boundary values
    epi_boundary = epi_n[boundary_ring]
    ale_boundary = ale_n[boundary_ring]

    if len(epi_boundary) == 0:
        epi_mask = epi_n > 0.5
        return False, 'no boundary ring pixels found', 0.0, epi_mask.astype(bool)

    # Compute epistemic dominance in boundary ring
    # epi > ale means model uncertainty dominates (correctable)
    n_epi_dom = int((epi_boundary > ale_boundary).sum())
    epi_ratio = n_epi_dom / (len(epi_boundary) + 1e-6)

    # Build epi_mask: boundary pixels where epistemic dominates
    # Use top 30% of epistemic values in boundary ring as focus
    if epi_boundary.max() > 0:
        epi_thresh = float(np.percentile(epi_boundary, 70))
        epi_mask   = (epi_n >= epi_thresh) & boundary_ring & (epi_n >= ale_n * 0.3)
    else:
        # Flat epistemic map — use full boundary ring as fallback
        epi_mask   = boundary_ring.copy()
        epi_ratio  = 0.5  # neutral

    # Decision: epi dominates if > 40% of boundary is epistemic
    # (lenient — N2 handles fine-grained filtering)
    if epi_ratio >= 0.40:
        reason = (f'epistemic dominant in boundary: {epi_ratio:.1%} '
                  f'of boundary pixels are correctable')
        return True, reason, epi_ratio, epi_mask.astype(bool)
    else:
        reason = (f'aleatoric dominant in boundary: only {epi_ratio:.1%} '
                  f'of boundary pixels are correctable (still passing to N2)')
        # Even for aleatoric: still pass epi_mask to N2 but with low ratio
        # N6 will reduce N2 budget accordingly
        return True, reason, epi_ratio, epi_mask.astype(bool)


