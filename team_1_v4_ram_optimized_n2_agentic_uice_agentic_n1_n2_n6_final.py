def n6_quality_summary(msa, n_pred, n_gt, mean_entropy):
    """Concise one-line quality readout for loop output."""
    grade = ('Excellent' if msa > 0.5 else
             'Good'      if msa > 0.35 else
             'Fair'      if msa > 0.2  else 'Poor')
    ratio = n_pred / max(n_gt, 1)
    note  = ('over-segmented'  if ratio > 1.3 else
             'under-segmented' if ratio < 0.7 else 'calibrated')
    return (f'[N6] {grade} | MSA={msa:.3f} | '
            f'N_pred={n_pred} N_gt={n_gt} ({note}) | ent={mean_entropy:.4f}')


