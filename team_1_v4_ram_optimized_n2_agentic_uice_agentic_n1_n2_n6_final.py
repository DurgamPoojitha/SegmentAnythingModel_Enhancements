        n6_reasons   = last_n6_log,
        iou_before   = last_diag.get('iou_before', 0.0),
        iou_after    = last_diag.get('iou_after', 0.0),
        n_epi_refined= n_epi_refined,
        n_ale_skipped= n_ale_reduced,
