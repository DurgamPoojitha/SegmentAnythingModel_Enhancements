"""### N2 — Automatic SAM Prompt Generation
**HOW to refine** (only on N1-approved epistemic regions)

N2 receives `epi_mask` from `n1_decide()` and:
1. Thresholds N1's epistemic map within the approved mask
2. Connected component analysis → epistemic boundary clusters
3. Centroid point prompts and bounding box prompts per cluster
4. Validates and clips all prompts to image bounds
5. Corrective SAM calls using auto-generated prompts

**Constraint:** N2 only runs if N1 returns `should_refine=True`.
All prompts are derived from the N1 epistemic mask — never from the full image.

"""

# =====================================================
# N2: Automatic SAM Prompt Generation
# =====================================================
# Runs SECOND — only when N1 returned should_refine=True.
# Input:  epi_map + epi_mask from n1_decide()
# Output: corrective SAM prompts → refined mask
#
# N2 never scans the full image independently.
# All cluster detection is restricted to N1's epi_mask.
# =====================================================

def n2_threshold_regions(epi_map, epi_mask, threshold_percentile=80):
    """
    N2 Step 1: Threshold N1's epistemic map within N1-approved mask.
    Uses percentile of values inside epi_mask only.
    Returns binary uint8 mask.
    """
    if epi_map is None or epi_map.size == 0 or not epi_mask.any():
        shape = epi_map.shape if epi_map is not None else (1, 1)
        return np.zeros(shape, dtype=np.uint8)
    epi_vals = epi_map[epi_mask]
    if len(epi_vals) == 0 or float(epi_vals.max()) < 1e-10:
        return np.zeros(epi_map.shape, dtype=np.uint8)
    thresh = float(np.percentile(epi_vals, threshold_percentile))
    return ((epi_map >= thresh) & epi_mask).astype(np.uint8)


def n2_extract_clusters(binary_mask, min_area=10, max_regions=3):
    """
    N2 Step 2: Connected component analysis on N1-gated epistemic mask.
    min_area=10 because we work on per-nucleus boundary regions.
    Returns list of cluster dicts sorted by area descending.
    """
    if binary_mask is None or int(binary_mask.sum()) == 0:
        return []
    labeled, n = label(binary_mask.astype(bool), return_num=True)
    if n == 0:
        return []
    clusters = []
    for p in regionprops(labeled):
        if p.area < min_area:
            continue
        y0, x0, y1, x1 = p.bbox
        cy, cx = p.centroid
        clusters.append({
            'centroid' : (int(cx), int(cy)),
            'bbox'     : (int(x0), int(y0), int(x1), int(y1)),
            'area'     : p.area,
        })
    return sorted(clusters, key=lambda c: c['area'], reverse=True)[:max_regions]


def n2_point_prompts(clusters, current_mask):
    """
    N2 Step 3a: Centroid point prompts from N1 epistemic clusters.
    Label = 1 (foreground) if centroid inside current mask, else 0.
    """
    if not clusters:
        return np.zeros((0, 2), dtype=np.float32), np.zeros(0, dtype=np.int32)
    pts, lbls = [], []
    for c in clusters:
        x, y = c['centroid']
        x, y = max(0, x), max(0, y)
        pts.append([float(x), float(y)])
        if (current_mask is not None
                and y < current_mask.shape[0]
                and x < current_mask.shape[1]):
            lbls.append(int(current_mask[y, x]))
        else:
            lbls.append(1)
    return np.array(pts, dtype=np.float32), np.array(lbls, dtype=np.int32)


def n2_box_prompts(clusters, img_shape, padding=3):
    """N2 Step 3b: Bounding box prompts around N1 epistemic clusters."""
    if not clusters:
        return []
    H, W = img_shape[:2]
    boxes = []
    for c in clusters:
        x0, y0, x1, y1 = c['bbox']
        box = np.array([
            max(0, x0 - padding), max(0, y0 - padding),
            min(W - 1, x1 + padding), min(H - 1, y1 + padding),
        ], dtype=np.float32)
        if box[2] > box[0] and box[3] > box[1]:
            boxes.append(box)
    return boxes


def n2_validate_prompts(point_coords, point_labels, boxes, img_shape):
    """N2 Step 4: Clip all coords to image bounds. Drop degenerate boxes."""
    H, W = img_shape[:2]
    if point_coords is not None and len(point_coords) > 0:
        point_coords = np.clip(point_coords, 0, [W - 1, H - 1])
    clean = []
    for b in (boxes or []):
        b = np.clip(b, 0, [W - 1, H - 1, W - 1, H - 1])
        if b[2] > b[0] and b[3] > b[1]:
            clean.append(b)
    return point_coords, point_labels, clean


def n2_corrective_sam(predictor, anchor_pt, point_coords, point_labels,
                       boxes, current_mask, current_score, n_iters=3):
    """
    N2 Step 5: SAM calls with N2-generated prompts.

    Anchor point (GT centroid) always included for localization.
    N2 corrective points (from N1 epistemic clusters) are appended.
    Box prompts tried individually for localized precision.
    Returns best mask found across all corrective calls.
    """
    best_mask  = current_mask.copy() if current_mask is not None else None
    best_score = current_score

    # Combined: anchor + N2 corrective points
    all_pts  = [[float(anchor_pt[0]), float(anchor_pt[1])]]
    all_lbls = [1]
    for pt, lbl in zip(point_coords, point_labels):
        all_pts.append([float(pt[0]), float(pt[1])])
        all_lbls.append(int(lbl))

    for _ in range(n_iters):
        try:
            with torch.no_grad():
                mp, sc, _ = predictor.predict(
                    point_coords=np.array(all_pts, dtype=np.float32),
                    point_labels=np.array(all_lbls, dtype=np.int32),
                    multimask_output=True)
            idx = int(np.argmax(sc))
            if float(sc[idx]) > best_score:
                best_score = float(sc[idx])
                best_mask  = mp[idx].astype(bool)
            del mp, sc
        except Exception:
            break

    for box in (boxes or []):
        try:
            with torch.no_grad():
                mp, sc, _ = predictor.predict(box=box, multimask_output=True)
            idx = int(np.argmax(sc))
            if float(sc[idx]) > best_score:
                best_score = float(sc[idx])
                best_mask  = mp[idx].astype(bool)
            del mp, sc
        except Exception:
            continue

    return best_mask, best_score


