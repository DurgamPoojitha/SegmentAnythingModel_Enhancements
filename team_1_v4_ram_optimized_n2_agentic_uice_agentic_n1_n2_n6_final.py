"""## N2 — Automatic SAM Prompt Generation from Entropy Maps

### Enhancement Overview
This section implements **autonomous SAM prompt generation** from uncertainty/entropy maps.
Instead of requiring manual prompts, the system:
1. Generates entropy maps from segmentation uncertainty
2. Automatically detects high-uncertainty regions (hotspots)
3. Derives **point prompts** (cluster centroids) and **box prompts** (bounding regions)
4. Feeds them into SAM — no human intervention required

This transforms UICE from a static refinement pipeline into an **agentic, self-correcting framework**.

"""

# =========================================================
# N2: Automatic SAM Prompt Generation from Entropy Maps
# =========================================================
# DESIGN FIX: Entropy is computed PER-NUCLEUS on the CROPPED
# mask region, not the full image. This gives meaningful
# spatial uncertainty about nucleus boundaries.
# All ops are lightweight numpy — RAM-safe.

# ── 1. Normalize entropy map ─────────────────────────────
def normalize_entropy_map(entropy_map):
    """Normalize entropy values to [0,1]. Handles zero-range safely."""
    if entropy_map is None or entropy_map.size == 0:
        return np.zeros_like(entropy_map, dtype=np.float32)
    e_min, e_max = float(entropy_map.min()), float(entropy_map.max())
    if e_max - e_min < 1e-8:
        return np.zeros_like(entropy_map, dtype=np.float32)
    return ((entropy_map - e_min) / (e_max - e_min)).astype(np.float32)


# ── 2. Threshold uncertain regions ───────────────────────
def threshold_uncertainty_regions(entropy_map, threshold_percentile=85):
    """
    Detect high-uncertainty BOUNDARY regions via percentile thresholding.
    Works on the normalized entropy map so threshold is always meaningful.
    Returns binary mask (H, W) uint8.
    """
    if entropy_map is None or entropy_map.size == 0:
        return np.zeros_like(entropy_map, dtype=np.uint8)
    normed = normalize_entropy_map(entropy_map)
    # Only threshold if there is real spread (not a flat map)
    if normed.max() < 0.1:
        return np.zeros(entropy_map.shape, dtype=np.uint8)
    thresh = float(np.percentile(normed[normed > 0], threshold_percentile)) if normed.max() > 0 else 1.0
    binary = (normed >= thresh).astype(np.uint8)
    return binary


# ── 3. Extract boundary uncertainty clusters ─────────────
def extract_uncertain_clusters(binary_mask, min_area=10, max_regions=3):
    """
    Connected component analysis on uncertain binary mask.
    min_area is small (10px) because we work on cropped nucleus regions.
    Returns list of dicts with mask, centroid, bbox, area.
    """
    if binary_mask is None or binary_mask.sum() == 0:
        return []
    labeled, n = label(binary_mask.astype(bool), return_num=True)
    if n == 0:
        return []
    clusters = []
    for p in regionprops(labeled):
        if p.area < min_area:
            continue
        y0, x0, y1, x1 = p.bbox
        cy, cx = p.centroid
        clusters.append({
            'mask':     (labeled == p.label).astype(np.uint8),
            'centroid': (int(cx), int(cy)),
            'bbox':     (int(x0), int(y0), int(x1), int(y1)),
            'area':     p.area,
        })
    clusters = sorted(clusters, key=lambda c: c['area'], reverse=True)[:max_regions]
    return clusters


# ── 4. Generate corrective point prompts ─────────────────
def generate_point_prompts(clusters, best_mask=None):
    """
    Returns SAM-compatible point prompts from cluster centroids.
    Labels: 1 if centroid is inside best_mask (foreground), else 0 (background).
    Format: coords [[x,y],...], labels [0/1,...]
    """
    if not clusters:
        return np.zeros((0, 2), dtype=np.float32), np.zeros(0, dtype=np.int32)
    points, labels_out = [], []
    for c in clusters:
        x, y = c['centroid']
        x, y = max(0, x), max(0, y)
        points.append([x, y])
        # Label: foreground if inside current best mask, else background
        if best_mask is not None and y < best_mask.shape[0] and x < best_mask.shape[1]:
            labels_out.append(int(best_mask[y, x]))
        else:
            labels_out.append(1)
    return np.array(points, dtype=np.float32), np.array(labels_out, dtype=np.int32)


# ── 5. Generate corrective box prompts ───────────────────
def generate_box_prompts(clusters, img_shape, padding=2):
    """
    Bounding boxes around uncertain boundary regions.
    Format: [[x_min, y_min, x_max, y_max], ...]
    """
    if not clusters:
        return []
    H, W = img_shape[:2]
    boxes = []
    for c in clusters:
        x0, y0, x1, y1 = c['bbox']
        x0 = max(0, x0 - padding)
        y0 = max(0, y0 - padding)
        x1 = min(W - 1, x1 + padding)
        y1 = min(H - 1, y1 + padding)
        if x1 > x0 and y1 > y0:
            boxes.append(np.array([x0, y0, x1, y1], dtype=np.float32))
    return boxes


# ── 6. Entropy-weighted cluster filter ───────────────────
def entropy_weighted_filter(clusters, entropy_map, max_regions=3):
    """Re-rank clusters by mean entropy within each cluster region."""
    if not clusters or entropy_map is None:
        return clusters
    normed = normalize_entropy_map(entropy_map)
    for c in clusters:
        # guard shape: cluster mask may be from a crop
        if c['mask'].shape == normed.shape:
            vals = normed[c['mask'].astype(bool)]
            c['entropy_weight'] = float(vals.mean()) if len(vals) > 0 else 0.0
        else:
            c['entropy_weight'] = 0.0
    return sorted(clusters, key=lambda c: c['entropy_weight'], reverse=True)[:max_regions]


# ── 7. Validate and clip SAM prompts ─────────────────────
def validate_sam_prompts(point_coords, point_labels, boxes, img_shape):
    """Clip all prompts to image boundaries. Drop degenerate entries."""
    H, W = img_shape[:2]
    if point_coords is not None and len(point_coords) > 0:
        point_coords = np.clip(point_coords, 0, [W - 1, H - 1])
    clean_boxes = []
    for box in (boxes or []):
        box = np.clip(box, 0, [W - 1, H - 1, W - 1, H - 1])
        if box[2] > box[0] and box[3] > box[1]:
            clean_boxes.append(box)
    return point_coords, point_labels, clean_boxes


