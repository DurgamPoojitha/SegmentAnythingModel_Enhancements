# =========================================================
# N2: Agentic Per-Nucleus Boundary Refinement
# =========================================================
# KEY FIX: Entropy is computed on the CROPPED nucleus mask
# region, revealing BOUNDARY uncertainty — not whole-image
# uncertainty which is always near-uniform for SAM.
#
# Pipeline per nucleus:
#   1. Initial SAM call (point + box from GT centroid)
#   2. Compute entropy map -> normalize -> detect boundary clusters
#   3. Generate corrective prompts from boundary uncertainty
#   4. Run iterative SAM correction with auto-prompts
#   5. Accept if improved; else keep original

@torch.no_grad()
def n2_agentic_refine(
    predictor,
    initial_masks_pred,        # (3, H, W) numpy — SAM candidates
    initial_scores,            # (3,) numpy
    img_shape,                 # (H, W) or (H, W, C)
    initial_point=None,        # (x, y) — the nucleus centroid used for init
    threshold_percentile=85,
    min_cluster_area=10,       # small: we work on cropped nucleus regions
    max_regions=3,
    entropy_threshold=0.05,    # lower: normalized entropy spreads to [0,1]
    n_correction_iters=3,      # how many corrective SAM calls
    visualize=False,
    image_rgb=None,
):
    """
    Per-nucleus boundary-focused agentic SAM refinement.

    Detects uncertain BOUNDARY pixels of the initial mask prediction,
    generates corrective prompts from those boundary clusters, and
    runs targeted SAM corrections to fix mask edges.

    Returns: best_mask (H,W bool), diagnostics dict
    """
    diag = {"n_clusters": 0, "n_points": 0, "n_boxes": 0,
            "entropy_max_normed": 0.0, "refined": False,
            "fallback": False, "iou_improvement": 0.0}

    H, W = img_shape[:2]

    # ── Guard ─────────────────────────────────────────────
    if initial_masks_pred is None or len(initial_masks_pred) == 0:
        diag["fallback"] = True
        return np.zeros((H, W), dtype=bool), diag

    # ── Step 1: Get best initial mask ─────────────────────
    best_idx  = int(np.argmax(initial_scores))
    best_mask = initial_masks_pred[best_idx].astype(bool)
    best_score = float(initial_scores[best_idx])

    # ── Step 2: Compute entropy map ───────────────────────
    entropy_map = compute_mask_entropy(initial_masks_pred, initial_scores)
    # nan/inf safety
    entropy_map = np.nan_to_num(entropy_map, nan=0.0, posinf=0.0, neginf=0.0)

    # Normalize to [0,1] — CRITICAL: raw entropy has tiny variance (~0.63±0.01)
    normed_entropy = normalize_entropy_map(entropy_map)
    diag["entropy_max_normed"] = float(normed_entropy.max())

    # ── Step 3: Focus on nucleus boundary region ──────────
    # Dilate the current mask to get the boundary context
    if best_mask.any():
        from skimage.morphology import binary_dilation, disk as _disk
        boundary_region = binary_dilation(best_mask, _disk(4)) & ~best_mask
        # Weight entropy by boundary region (ignore interior — it's always confident)
        boundary_entropy = normed_entropy.copy()
        boundary_entropy[~boundary_region] = 0.0
    else:
        boundary_entropy = normed_entropy
        boundary_region  = np.ones((H, W), dtype=bool)

    # ── Step 4: Detect uncertain boundary clusters ────────
    if boundary_entropy.max() < entropy_threshold:
        # Boundary is confident — no refinement needed
        del entropy_map, normed_entropy, boundary_entropy
        return best_mask, diag

    binary_mask = threshold_uncertainty_regions(boundary_entropy, threshold_percentile)
    clusters    = extract_uncertain_clusters(binary_mask, min_area=min_cluster_area,
                                             max_regions=max_regions)
    clusters    = entropy_weighted_filter(clusters, boundary_entropy, max_regions=max_regions)
    del binary_mask, boundary_entropy

    diag["n_clusters"] = len(clusters)

    if not clusters:
        del entropy_map, normed_entropy
        return best_mask, diag

    # ── Step 5: Generate corrective prompts ───────────────
    point_coords, point_labels = generate_point_prompts(clusters, best_mask)
    boxes                      = generate_box_prompts(clusters, img_shape, padding=2)
    point_coords, point_labels, boxes = validate_sam_prompts(
        point_coords, point_labels, boxes, img_shape)

    diag["n_points"] = len(point_coords)
    diag["n_boxes"]  = len(boxes)

    if visualize and image_rgb is not None:
        visualize_generated_prompts(image_rgb, normed_entropy, clusters,
                                    point_coords, boxes, show=True)
    del normed_entropy, entropy_map

    # ── Step 6: Iterative SAM correction ─────────────────
    # Build prompt list starting from the original nucleus centroid
    # and appending boundary corrective points
    if initial_point is not None:
        all_pts    = [[float(initial_point[0]), float(initial_point[1])]]
        all_labels = [1]
    else:
        all_pts, all_labels = [], []

    # Add boundary corrective points
    for pt, lbl in zip(point_coords, point_labels):
        all_pts.append([float(pt[0]), float(pt[1])])
        all_labels.append(int(lbl))

    for _iter in range(n_correction_iters):
        try:
            mp, sc, _ = predictor.predict(
                point_coords=np.array(all_pts),
                point_labels=np.array(all_labels),
                multimask_output=True
            )
            cand_idx   = int(np.argmax(sc))
            cand_mask  = mp[cand_idx].astype(bool)
            cand_score = float(sc[cand_idx])

            if cand_score > best_score:
                best_score = cand_score
                best_mask  = cand_mask
                diag["refined"] = True

            del mp, sc

            # Recompute boundary uncertainty on updated mask for next iter
            if _iter < n_correction_iters - 1 and best_mask.any():
                from skimage.morphology import binary_dilation, disk as _disk2
                new_boundary = binary_dilation(best_mask, _disk2(3)) & ~best_mask
                # Add the most uncertain remaining boundary pixel as next prompt
                emap_fresh = compute_mask_entropy(
                    np.stack([best_mask.astype(np.float32),
                              (~best_mask).astype(np.float32),
                              best_mask.astype(np.float32)]),
                    np.array([best_score, 0.5, best_score])
                )
                emap_fresh[~new_boundary] = 0.0
                if emap_fresh.max() > 0:
                    idx = int(emap_fresh.argmax())
                    py, px = np.unravel_index(idx, emap_fresh.shape)
                    all_pts.append([float(px), float(py)])
                    all_labels.append(1 if best_mask[py, px] else 0)
                del emap_fresh

        except Exception as e:
            break

    return best_mask, diag

